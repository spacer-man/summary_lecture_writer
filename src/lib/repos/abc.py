from typing import Protocol, Sequence


class Repository[T, T_id](Protocol):
    async def get_one(self, *args, **properties)  -> T | None:    ...
    async def get_many(self, *args, **properties) -> Sequence[T]: ...
    async def add(self, obj: T)                   -> T_id:        ...
    async def update(self, obj: T)                -> None:        ...
    async def remove(self, *args, **properties)   -> Sequence[T]: ...
    async def commit(self)                        -> None:        ...
